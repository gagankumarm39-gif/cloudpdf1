"""
Comprehensive Automated Test Suite for Milestone 2 - PDF Generation Engine
Tests:
1. Valid document input generates a binary with valid PDF signature (%PDF-)
2. Multi-page document generation handles page numbers and text flow correctly
3. Validation errors on empty title, author, or content (HTTP 400)
4. Invalid/empty payload handling
5. Binary download response with proper headers (mimetype=application/pdf)
6. Download of generated file via /api/download-pdf/<filename>
7. Non-existent file download returns 404
"""
import io
import pytest
from app import app
from services.pdf_service import PDFGeneratorService
from services.storage_service import StorageService, sanitize_filename


def test_sanitize_filename():
    assert sanitize_filename("My Project: Version 1.0 / Test?") == "My_Project_Version_10_Test"
    assert sanitize_filename("   ") == "document"
    assert sanitize_filename("../../../etc/passwd") == "etcpasswd"


def test_pdf_service_direct_generation():
    service = PDFGeneratorService()
    title = "Direct Unit Test Document"
    author = "Kavya M"
    description = "Test description"
    content = "This is a unit test content line.\nAnother paragraph to check spacing."
    doc_id = "DOC-TEST-1"

    pdf_bytes = service.generate_pdf(
        title=title,
        author=author,
        description=description,
        content=content,
        doc_id=doc_id
    )

    assert isinstance(pdf_bytes, bytes)
    assert len(pdf_bytes) > 1000
    # Must start with standard PDF signature
    assert pdf_bytes.startswith(b"%PDF-"), "Generated byte sequence does not start with %PDF- header"


def test_pdf_service_multipage_flow():
    service = PDFGeneratorService()
    title = "Extensive Multi-Page Report"
    author = "Architect"
    description = "Stress test for pagination and two-pass numbering"
    # Create sufficient content to span across 3+ pages
    paragraphs = [f"SECTION {i}\n" + ("This is paragraph content designed to test multi-page flow. " * 30) for i in range(1, 10)]
    content = "\n\n".join(paragraphs)

    pdf_bytes = service.generate_pdf(
        title=title,
        author=author,
        description=description,
        content=content,
        doc_id="DOC-MULTI-PAGE"
    )

    assert pdf_bytes.startswith(b"%PDF-")
    # Verify presence of multiple pages in the PDF object count
    assert len(pdf_bytes) > 5000


def test_api_generate_pdf_success_download():
    client = app.test_client()

    payload = {
        "title": "Cloud Computing Milestone 2 Test",
        "author": "Kavya M",
        "description": "Integration test for POST /api/generate-pdf",
        "content": "Validating full pipeline from HTTP request to ReportLab rendering and download response."
    }

    response = client.post("/api/generate-pdf?download=true", json=payload)
    assert response.status_code == 200
    assert response.mimetype == "application/pdf"
    assert response.data.startswith(b"%PDF-")
    assert "X-Doc-Id" in response.headers
    assert "X-Doc-Filename" in response.headers
    assert response.headers["X-Doc-Title"] == "Cloud Computing Milestone 2 Test"


def test_api_generate_pdf_success_json_mode():
    client = app.test_client()

    payload = {
        "title": "JSON Mode Generation",
        "author": "System Architect",
        "description": "Testing JSON metadata response mode",
        "content": "Testing response without direct attachment streaming."
    }

    response = client.post("/api/generate-pdf?download=false", json=payload)
    assert response.status_code == 201
    data = response.get_json()
    assert data["success"] is True
    assert "document" in data
    assert data["document"]["title"] == "JSON Mode Generation"
    assert "download_url" in data

    # Verify we can download that file through the returned URL
    download_url = data["download_url"]
    download_res = client.get(download_url)
    assert download_res.status_code == 200
    assert download_res.mimetype == "application/pdf"
    assert download_res.data.startswith(b"%PDF-")


def test_api_generate_pdf_validation_missing_fields():
    client = app.test_client()

    # Empty title
    res1 = client.post("/api/generate-pdf", json={"title": "", "author": "User", "content": "Sample"})
    assert res1.status_code == 400
    assert "title" in res1.get_json()["details"]

    # Empty author
    res2 = client.post("/api/generate-pdf", json={"title": "Title", "author": "", "content": "Sample"})
    assert res2.status_code == 400
    assert "author" in res2.get_json()["details"]

    # Empty content
    res3 = client.post("/api/generate-pdf", json={"title": "Title", "author": "User", "content": "  "})
    assert res3.status_code == 400
    assert "content" in res3.get_json()["details"]


def test_api_download_nonexistent_file():
    client = app.test_client()
    res = client.get("/api/download-pdf/non_existent_file_9999.pdf")
    assert res.status_code == 404
